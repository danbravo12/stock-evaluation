"""Repeat-run variability of the qualitative agent (live, free tier; not part of the replay fixtures).

    .venv/bin/python scripts/qualitative_variability.py [N]     # N extra runs of the 5 tickers, default 2 (about 35 requests each)

Runs the same prompts as the recorded run at temperature 0 with the response store bypassed (LLMClient use_store=False: nothing is
read from or written to fixtures or cache), then compares with the recorded findings (replayed) and writes docs/qualitative_variability.md.
Refuses when PAID_MODE_ENABLED=true and stops, writing nothing, if today's ledger count would exceed MAX_REQUESTS_TODAY.
"""
from __future__ import annotations

import json
import sys
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.agents.qualitative import assess_qualitative  # noqa: E402
from engine.contracts import QUAL_CRITERIA, QualFindings  # noqa: E402
from engine.fetch.edgar import EdgarClient  # noqa: E402
from engine.llm.budget import Ledger, QuotaReached, pacific_day  # noqa: E402
from engine.llm.client import LLMClient  # noqa: E402
from engine.retrieve import Retriever  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402
from engine.trace import TraceRecorder  # noqa: E402

OUT = REPO_ROOT / "docs" / "qualitative_variability.md"
MAX_REQUESTS_TODAY = 400
PER_COMPANY_WORST_CASE = 12  # requests a company can take (typically 5-9)
SHORT = {"evidence found": "found", "evidence weak": "weak", "insufficient evidence": "insufficient", "not assessed": "not assessed"}


def cited(f) -> frozenset:
    return frozenset(c.passage_id for c in f.citations)


def main(n_runs: int) -> int:
    settings = Settings.from_env()
    if settings.paid_mode_enabled:
        print("PAID_MODE_ENABLED=true: refusing. This runs on the free tier only.")
        return 2
    retriever = Retriever(EdgarClient("replay", settings))
    tickers = json.loads((REPO_ROOT / "config" / "test_tickers.json").read_text())["tickers"]
    ciks = {t: retriever.client.lookup_cik(t)[0] for t in tickers}

    replay = LLMClient("replay", settings)
    runs: list[dict[str, QualFindings]] = [{t: assess_qualitative(ciks[t], t, retriever, replay, TraceRecorder("rec")) for t in tickers}]

    trace_dir = REPO_ROOT / "data" / "cache" / "trace"
    ledger = Ledger(settings.ledger_path)
    live = LLMClient("live", settings, use_store=False, trace=TraceRecorder("variability", trace_dir / "qualitative_variability.jsonl"))
    for r in range(1, n_runs + 1):
        runs.append({})
        for t in tickers:
            used = ledger.__class__(settings.ledger_path).requests_today(live.profile_name, pacific_day(datetime.now(timezone.utc)))
            if used + PER_COMPANY_WORST_CASE > MAX_REQUESTS_TODAY:
                print(f"STOPPED before run {r} {t}: {used} requests today; the limit for this script is {MAX_REQUESTS_TODAY}. Nothing written.")
                return 1
            try:
                runs[r][t] = assess_qualitative(ciks[t], t, retriever, live, live.trace)
            except QuotaReached as e:
                print(f"STOPPED: {e}. Nothing written.")
                return 1
            print(f"run {r} {t}: " + ", ".join(SHORT[f.verdict] for f in runs[r][t].findings), flush=True)

    rows, identical, moved, same_passage = [], 0, [], 0
    for t in tickers:
        for k, crit in enumerate(QUAL_CRITERIA):
            fs = [run[t].findings[k] for run in runs]
            verdicts = [f.verdict for f in fs]
            agree = Counter(verdicts).most_common(1)[0][1]
            sets = [cited(f) for f in fs]
            passage = "–" if not any(sets) else ("same" if all(s == sets[0] for s in sets) else "changed")
            same_passage += passage == "same"
            if agree == len(fs):
                identical += 1
            else:
                moved.append(f"{t} {crit}: " + " → ".join(SHORT[v] for v in verdicts))
            rows.append(f"| {t} | {crit} | " + " | ".join(SHORT[v] for v in verdicts) + f" | {agree}/{len(fs)} | {passage} |")
    total = len(tickers) * len(QUAL_CRITERIA)
    head = " | ".join(["recorded"] + [f"run {r}" for r in range(1, n_runs + 1)])
    lines = ["# Qualitative agent: repeat-run variability", "",
             "**Research output, not financial advice.** Generated by `scripts/qualitative_variability.py` on "
             f"{datetime.now(timezone.utc).date().isoformat()} (live, free tier). Not reproducible offline: it measures what the API returns when the same "
             "request is sent again. The recorded run is the one in `docs/qualitative_report.md`; the extra runs use the same prompts, rubric and "
             "temperature 0, with the response store bypassed so every call is a fresh request.", "",
             f"**Verdicts identical across all {len(runs)} runs in {identical} of {total} findings.**", ""]
    if moved:
        lines += ["Moved: " + "; ".join(moved) + ".", ""]
    lines += [f"| Company | Criterion | {head} | Agreement | Cited passage |", "|---|---|" + "---|" * (len(runs) + 2)] + rows + [""]
    lines += ["“Agreement” is the size of the largest group of equal verdicts. “Cited passage” compares the set of passages cited across runs "
              f"(same in {same_passage} findings; “–” when no run cited anything).", "", "## Calls and tokens per run", "",
              "| Run | Model calls | Input tokens | Output tokens | Notional cost | Actual cost |", "|---|---|---|---|---|---|"]
    for r, run in enumerate(runs):
        tot = [x.totals for x in run.values()]
        lines.append(f"| {head.split(' | ')[r]} | {sum(x.llm_calls for x in tot)} | {sum(x.usage.prompt_tokens for x in tot):,} | {sum(x.usage.completion_tokens for x in tot):,} | "
                     f"${sum(x.notional_cost_usd for x in tot):.4f} | ${sum(x.actual_cost_usd for x in tot):.4f} |")
    if len({(sum(f.totals.usage.prompt_tokens for f in run.values()), sum(f.totals.usage.completion_tokens for f in run.values())) for run in runs}) == 1:
        lines += ["", "Token counts are identical in every run, so the API returned the same replies to the same requests: at temperature 0 this model is "
                  "reproducible for identical prompts. That is not the same as stable under changes: the earlier prompt revisions moved several verdicts "
                  "(`docs/evaluation_notes.md` item 11), so the labels depend on prompt wording and rubric text more than on API noise."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}: identical in {identical} of {total}")
    return 0


if __name__ == "__main__":
    sys.exit(main(int(sys.argv[1]) if len(sys.argv) > 1 else 2))
