"""Where the SIC-derived sector class (ADR-033) and GICS disagree for the S&P 500 snapshot -> docs/universe_report.md.

    .venv/bin/python scripts/universe_report.py --fetch-sic   # live, once: SEC submissions for every CIK -> data/universe/sic_<date>.csv (small, committed)
    .venv/bin/python scripts/universe_report.py               # offline: write the report from the two CSVs

Evidence only: no behaviour changes. The engine keeps using the SIC class (ADR-033); this shows what a GICS-based class would change.
"""
from __future__ import annotations

import csv
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.score.common import load_sector_rules, sector_class  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402
from engine.universe import UNIVERSE_DIR, load_universe  # noqa: E402

OUT = REPO_ROOT / "docs" / "universe_report.md"


def gics_class(sector: str, sub: str) -> str:
    """The ADR-013 exception class a GICS row implies: banks, insurers, and all Utilities."""
    if sub in ("Diversified Banks", "Regional Banks"):
        return "bank"
    if "Insurance" in sub or sub == "Reinsurance":
        return "insurer"
    if sector == "Utilities":
        return "utility"
    return "other"


def fetch_sic(u) -> Path:
    from engine.fetch.edgar import EdgarClient
    client = EdgarClient("live", Settings.from_env())
    out = UNIVERSE_DIR / f"sic_{u.snapshot_date}.csv"
    with out.open("w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["cik", "sic", "sic_description"])
        for i, r in enumerate(u.primary, start=1):
            s = client.submissions(r.cik)
            w.writerow([r.cik, s.get("sic") or "", s.get("sicDescription") or ""])
            if i % 50 == 0:
                print(f"{i}/{len(u.primary)}", flush=True)
    return out


def main(fetch: bool) -> int:
    u = load_universe()
    if fetch:
        print("wrote", fetch_sic(u).relative_to(REPO_ROOT))
    sic_path = UNIVERSE_DIR / f"sic_{u.snapshot_date}.csv"
    with sic_path.open(newline="", encoding="utf-8") as f:
        sic = {r["cik"]: r for r in csv.DictReader(f)}
    rules = load_sector_rules()
    rows = []
    for r in u.primary:
        s = sic.get(r.cik, {})
        sc = sector_class(s.get("sic") or None, rules)
        gc = gics_class(r.gics_sector, r.gics_sub_industry)
        rows.append((r, s.get("sic", ""), s.get("sic_description", ""), sc, gc))
    mismatch = [x for x in rows if x[3] != x[4]]
    fin_other = [x for x in rows if x[0].gics_sector == "Financials" and x[3] == "other" and x[4] == "other"]
    L = ["# Universe report: S&P 500 snapshot and sector classes", "",
         f"{u.attribution}. SIC codes: U.S. Securities and Exchange Commission, EDGAR (public domain). Generated by `scripts/universe_report.py` from "
         f"`data/universe/sp500_{u.snapshot_date}.csv` and `data/universe/sic_{u.snapshot_date}.csv`. Research output, not financial advice.", "",
         f"- Rows in the snapshot: **{len(u.rows)}**; analysed once per CIK: **{len(u.primary)}** (dual share classes: "
         + ", ".join("/".join(g) for g in u.dual_class_groups()) + f"; primary symbols {sorted(u.primary_symbols)}, ADR-053).",
         f"- Sector class counts, SIC-derived (what the engine uses, ADR-033): " + ", ".join(f"{k} {v}" for k, v in sorted(Counter(x[3] for x in rows).items())) + ".",
         f"- Sector class counts, GICS-derived (banks = Diversified/Regional Banks; insurers = any Insurance sub-industry; utilities = the Utilities sector, which also holds gas, water and power producers): "
         + ", ".join(f"{k} {v}" for k, v in sorted(Counter(x[4] for x in rows).items())) + ".",
         f"- **Disagreements: {len(mismatch)} of {len(rows)}.**", "",
         "## Disagreements", "", "A company is listed when the SIC class (what ADR-013 exceptions use today) differs from the GICS-implied class.", "",
         "| Symbol | Company | GICS sub-industry | SIC | SIC description | SIC class | GICS class |", "|---|---|---|---|---|---|---|"]
    for r, code, desc, sc, gc in sorted(mismatch, key=lambda x: (x[3], x[4], x[0].symbol)):
        L.append(f"| {r.symbol} | {r.security} | {r.gics_sub_industry} | {code} | {desc} | {sc} | {gc} |")
    L += ["", "## Financials the exceptions do not cover", "",
          "GICS Financials classed \"other\" by both rules (asset managers, brokers, exchanges, consumer finance, insurance-adjacent). Their statements are bank-like or unlike an industrial's, "
          "so G2 and B2 to B4 may mislead; ADR-013 does not exempt them. Listed for a later decision.", "",
          "| Symbol | Company | GICS sub-industry | SIC description |", "|---|---|---|---|"]
    for r, code, desc, sc, gc in sorted(fin_other, key=lambda x: (x[0].gics_sub_industry, x[0].symbol)):
        L.append(f"| {r.symbol} | {r.security} | {r.gics_sub_industry} | {desc} |")
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {len(mismatch)} disagreements, {len(fin_other)} other financials")
    return 0


if __name__ == "__main__":
    sys.exit(main("--fetch-sic" in sys.argv))
