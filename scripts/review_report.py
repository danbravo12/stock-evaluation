"""Explainer + Critic on the 5 test tickers, scored against the qualitative gold set -> docs/critic_report.md.

    .venv/bin/python scripts/review_report.py record [TICKER ...]   # live, free tier: explainer, critic, retries, fault cases (about 30-40 requests)
    .venv/bin/python scripts/review_report.py replay                # offline, identical report

The qualitative findings come from the recorded v1.1 run (replayed from fixtures); only the new calls are recorded. Refuses in paid mode;
stops cleanly if today's ledger count would pass 400. Also writes data/cache/trace/review_<mode>.jsonl and the fixture hashes used.
"""
