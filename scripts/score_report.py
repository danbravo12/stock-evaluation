"""Score the 5 test companies from the fixtures (replay, no network) and write
docs/scorecard_report.md: a summary table, then per company every criterion with its
figures, threshold, years, flags and the source filing of every input.

    .venv/bin/python scripts/score_report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.fetch.edgar import EdgarClient  # noqa: E402
from engine.score import score_ticker  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402

OUT = REPO_ROOT / "docs" / "scorecard_report.md"
SHORT = {"pass": "pass", "fail": "fail", "partial_pass": "partial", "not_applicable": "n/a", "not_meaningful": "n/m", "data_gap": "gap"}
IDS = ["G1", "G2", "G3", "G4", "G5", "G6", "G7", "B1", "B2", "B3", "B4"]


def fmt(v) -> str:
    if isinstance(v, bool) or v is None or isinstance(v, str):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(fmt(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{k}: {fmt(x)}" for k, x in v.items()) + "}"
    if isinstance(v, int):
        return str(v)
    return f"{v:,.0f}" if abs(v) >= 1e4 else f"{v:.4g}"


def main() -> None:
    client = EdgarClient("replay", Settings.from_env())
    tickers = json.loads((REPO_ROOT / "config" / "test_tickers.json").read_text())["tickers"]
    scores = {t: score_ticker(client, t) for t in tickers}

    lines = [
        "# Scorecard report",
        "",
        "Generated by `scripts/score_report.py` from the recorded fixtures (replay mode, no network, no price). "
        "Research output only, not financial advice. Data: U.S. Securities and Exchange Commission, EDGAR (public domain).",
        "",
        "Labels: pass · fail · partial (G4 pass on a partial record) · n/a (not applicable, ADR-013) · n/m (not meaningful) · gap (data gap). "
        "G6 and G7 need a price (Finnhub, later).",
        "",
        "## Summary",
        "",
        "| Company | Sector | " + " | ".join(IDS) + " | Graham | Buffett (quant.) | Gaps | % met |",
        "|---|---|" + "---|" * len(IDS) + "---|---|---|---|",
    ]
    for t, s in scores.items():
        by_id = {r.id: r for r in s.results}
        pct = f"{s.summary.percent_met:.0%}" if s.summary.percent_met is not None else "-"
        lines.append(f"| {t} (FY{s.as_of_year}) | {s.sector_class} | " + " | ".join(SHORT[by_id[i].label] for i in IDS)
                     + f" | {s.summary.graham_met}/{s.summary.graham_applicable} | {s.summary.buffett_met}/{s.summary.buffett_applicable}"
                     + f" | {s.summary.data_gaps} | {pct} |")

    for t, s in scores.items():
        lines += ["", f"## {t}", "", f"CIK {s.cik} · sector class **{s.sector_class}** · as-of fiscal year **{s.as_of_year}**", ""]
        for r in s.results:
            label = SHORT[r.label] + (f" ({r.year_label})" if r.year_label else "")
            lines.append(f"### {r.id} {r.name}: {label}")
            lines.append(f"- Threshold: {r.threshold}")
            if r.reason:
                lines.append(f"- Reason: {r.reason}")
            if r.figures:
                lines.append("- Figures: " + "; ".join(f"{k} = {fmt(v)}" for k, v in r.figures.items()))
            if r.years:
                lines.append(f"- Years: {r.years[0]}–{r.years[-1]} ({len(r.years)})" if len(r.years) > 3 else f"- Years: {r.years}")
            if r.by_year:
                lines.append("- By year: " + "; ".join(f"{y}: {fmt(v)}" for y, v in r.by_year.items()))
            if r.flags:
                lines.append("- Flags: " + ", ".join(r.flags))
            lines.append("")
        lines += ["<details><summary>Inputs and sources</summary>", "",
                  "| Measure | Fiscal year | Value | Concept | Filing | Flags |", "|---|---|---|---|---|---|"]
        for i in s.inputs:
            lines.append(f"| {i.measure} | {i.fiscal_year} | {fmt(i.value)} | {i.concept} | [{i.accession}]({i.source_url}) | {', '.join(i.flags)} |")
        lines += ["", "</details>"]

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
