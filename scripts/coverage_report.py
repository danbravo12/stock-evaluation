"""Run the fact normaliser on the 5 fixtures (replay, no network) and write
docs/coverage_report.md: what was found per measure and company, and what is missing.

    .venv/bin/python scripts/coverage_report.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.fetch.edgar import EdgarClient  # noqa: E402
from engine.normalise import load_concept_map, normalise_from_store  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402

OUT = REPO_ROOT / "docs" / "coverage_report.md"


def cell(series) -> str:
    if not series.values:
        return "none"
    years = [v.fiscal_year_end.year for v in series.values]
    return f"{min(years)}–{max(years)} ({len(years)})"


def main() -> None:
    client = EdgarClient("replay", Settings.from_env())
    concept_map = load_concept_map()
    tickers = json.loads((REPO_ROOT / "config" / "test_tickers.json").read_text())["tickers"]
    results = {}
    for t in tickers:
        cik, _ = client.lookup_cik(t)
        results[t] = normalise_from_store(client, cik, concept_map)

    lines = [
        "# Fact normaliser: coverage report",
        "",
        "Generated by `scripts/coverage_report.py` from the recorded fixtures (replay mode, no network). "
        "Years are fiscal years labelled by period end date; each cell is first–last year (number of annual values). "
        "Data: U.S. Securities and Exchange Commission, EDGAR (public domain).",
        "",
        "## Years covered",
        "",
        "| Measure | " + " | ".join(tickers) + " |",
        "|---|" + "---|" * len(tickers),
    ]
    for m in concept_map["measures"]:
        lines.append(f"| {m} | " + " | ".join(cell(results[t].series[m]) for t in tickers) + " |")

    lines += ["", "## Concepts used, restatements, gaps and notes", ""]
    for m, spec in concept_map["measures"].items():
        lines += [f"### {m}", "", f"_{spec['_notes']}_", ""]
        for t in tickers:
            s = results[t].series[m]
            used: dict[str, int] = {}
            for v in s.values:
                used[v.concept] = used.get(v.concept, 0) + 1
            concepts = ", ".join(f"`{c}` ×{n}" for c, n in used.items()) or "none"
            restated = sum(v.restated for v in s.values)
            derived = sum(v.derived for v in s.values)
            line = f"- **{t}**: {concepts}; restated {restated}"
            if derived:
                line += f"; derived {derived}"
            lines.append(line)
            for reason in sorted({g.reason for g in s.gaps}):
                years = [g.fiscal_year_end for g in s.gaps if g.reason == reason]
                if years[0] is None:
                    lines.append(f"  - gap (whole measure): {reason}")
                else:
                    span = ", ".join(str(y.year) for y in years)
                    lines.append(f"  - gap {len(years)} yr ({span}): {reason}")
            if s.notes:
                lines.append(f"  - {len(s.notes)} note(s), e.g. {s.notes[0]}")
        lines.append("")

    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
