"""Run the qualitative Buffett agent on the 5 test tickers and write docs/qualitative_report.md.

    .venv/bin/python scripts/qualitative_report.py record    # live, free tier: writes fixtures/llm/ (expect ~30-60 requests)
    .venv/bin/python scripts/qualitative_report.py replay    # offline: same runs from the fixtures, zero network, identical report
    (optionally followed by tickers, e.g. `record KO`, to run a subset; the committed report is always the full replay)

Refuses to record when PAID_MODE_ENABLED=true. Stops cleanly (no partial report) if the daily quota is reached.
Also writes data/cache/trace/qualitative_<mode>.jsonl (git-ignored) and the list of fixture hashes this run used
(data/cache/trace/qualitative_used_hashes.txt), so orphaned fixtures can be pruned after a re-record.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.agents.qualitative import assess_qualitative  # noqa: E402
from engine.contracts import QUAL_CRITERIA, QualFindings  # noqa: E402
from engine.fetch.edgar import EdgarClient  # noqa: E402
from engine.llm.budget import Ledger, QuotaReached  # noqa: E402
from engine.llm.client import LLMClient  # noqa: E402
from engine.retrieve import Retriever  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402
from engine.trace import TraceRecorder  # noqa: E402

OUT = REPO_ROOT / "docs" / "qualitative_report.md"
TRACE_DIR = REPO_ROOT / "data" / "cache" / "trace"
SHORT = {"evidence found": "found", "evidence weak": "weak", "insufficient evidence": "insufficient", "not assessed": "not assessed"}
REASON = {"section_missing": "section missing", "turn_cap": "turn cap reached", "invalid_citation": "invalid citation pointers", "llm_output_error": "malformed model output"}


def flat(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def company_section(fs: QualFindings) -> list[str]:
    lines = [f"## {fs.ticker}", "", f"10-K accession `{fs.accession}` · {fs.totals.llm_calls} model calls, {fs.totals.tool_calls} tool calls, "
             f"{fs.totals.usage.total_tokens:,} tokens, notional ${fs.totals.notional_cost_usd:.4f}, actual ${fs.totals.actual_cost_usd:.4f}", ""]
    for f in fs.findings:
        if f.verdict == "not assessed":
            lines += [f"### {fs.ticker} · {f.criterion}: _not assessed — {REASON[f.stop_reason]}_", "",
                      f"The system could not judge this criterion (this says nothing about the filing). {f.rationale}", ""]
        else:
            lines += [f"### {fs.ticker} · {f.criterion}: **{f.verdict}**", "", f.rationale, ""]
        for c in f.citations:
            lines += [f"> {flat(c.quote).replace(chr(92) + '|', '|')}", f"> — accession `{c.accession}`, Item {c.item}, passage `{c.passage_id}`, "
                      f"sentences {c.sentences[0]}–{c.sentences[1]}, characters {c.char_start}–{c.char_end}", ""]
        searches = "; ".join(("seeded " if s.seeded else "") + f"\"{' / '.join(s.queries) if not s.seeded else ', '.join(s.queries)}\" in items {', '.join(s.items) if s.items else 'all'}"
                             f" → {len(s.passage_ids)} hits" for s in f.searches) or "none"
        lines += [f"Searches: {searches}", "",
                  f"Stop: `{f.stop_reason}` · model calls {f.llm_calls} · tool calls {f.tool_calls} · tokens {f.usage.prompt_tokens:,} in / "
                  f"{f.usage.completion_tokens:,} out · notional ${f.notional_cost_usd:.4f}", ""]
    return lines


def render(results: list[QualFindings]) -> str:
    lines = ["# Qualitative agent report", "",
             "**Research output, not financial advice.** Verdicts describe what each company's latest 10-K says, judged by an LLM against a fixed rubric "
             "(`config/search_terms.json`); they are not recommendations. Generated by `scripts/qualitative_report.py` (record once, replay offline). "
             "Citations are sentence pointers; the quoted text and offsets are built by code from them (ADR-046) and refer to the normalised 10-K text (ADR-035); line breaks inside a quote are shown as spaces. "
             "\"Insufficient evidence\" means the filing, as retrieved, does not show the criterion; \"not assessed\" means the system could not judge it (ADR-047). "
             "Data: U.S. Securities and Exchange Commission, EDGAR (public domain).", "",
             "## Summary", "", "| Company | " + " | ".join(QUAL_CRITERIA) + " |", "|---|" + "---|" * len(QUAL_CRITERIA)]
    for fs in results:
        lines.append(f"| {fs.ticker} | " + " | ".join(SHORT[f.verdict] if f.verdict != "not assessed" else f"_not assessed — {REASON[f.stop_reason]}_" for f in fs.findings) + " |")
    findings = [f for fs in results for f in fs.findings]
    counts = {v: sum(f.verdict == v for f in findings) for v in SHORT}
    lines += ["", f"Of {len(findings)} findings: " + ", ".join(f"{n} {SHORT[v]}" for v, n in counts.items()) + ".", "", "## Calls and tokens per company", "",
              "Model calls are the requests that count against the free-tier quota; tool calls include the seeded search and `submit_finding` and cost nothing. "
              "Notional cost is tokens at the paid price; actual cost is what was billed.", "",
              "| Company | Model calls | Tool calls | Input tokens | Output tokens | Total tokens | Notional cost | Actual cost |", "|---|---|---|---|---|---|---|---|"]
    for fs in results:
        t = fs.totals
        lines.append(f"| {fs.ticker} | {t.llm_calls} | {t.tool_calls} | {t.usage.prompt_tokens:,} | {t.usage.completion_tokens:,} | {t.usage.total_tokens:,} | "
                     f"${t.notional_cost_usd:.4f} | ${t.actual_cost_usd:.4f} |")
    n = len(results)
    mean = lambda f: sum(f(fs.totals) for fs in results) / n  # noqa: E731
    lines.append(f"| **Mean** | {mean(lambda t: t.llm_calls):.1f} | {mean(lambda t: t.tool_calls):.1f} | {mean(lambda t: t.usage.prompt_tokens):,.0f} | "
                 f"{mean(lambda t: t.usage.completion_tokens):,.0f} | {mean(lambda t: t.usage.total_tokens):,.0f} | ${mean(lambda t: t.notional_cost_usd):.4f} | "
                 f"${mean(lambda t: t.actual_cost_usd):.4f} |")
    lines.append(f"| **Total** | {sum(r.totals.llm_calls for r in results)} | {sum(r.totals.tool_calls for r in results)} | "
                 f"{sum(r.totals.usage.prompt_tokens for r in results):,} | {sum(r.totals.usage.completion_tokens for r in results):,} | "
                 f"{sum(r.totals.usage.total_tokens for r in results):,} | ${sum(r.totals.notional_cost_usd for r in results):.4f} | "
                 f"${sum(r.totals.actual_cost_usd for r in results):.4f} |")
    lines.append("")
    for fs in results:
        lines += company_section(fs)
    return "\n".join(lines) + "\n"


def main(mode: str, only: list[str]) -> int:
    if mode not in ("record", "replay"):
        print(__doc__)
        return 2
    settings = Settings.from_env()
    if mode == "record" and settings.paid_mode_enabled:
        print("PAID_MODE_ENABLED=true: refusing to record. Recording uses the free tier only; unset it in .env.")
        return 2
    TRACE_DIR.mkdir(parents=True, exist_ok=True)
    trace_path = TRACE_DIR / f"qualitative_{mode}.jsonl"
    trace_path.unlink(missing_ok=True)
    trace = TraceRecorder(f"qualitative-{mode}", trace_path)
    llm = LLMClient(mode, settings, trace=trace)
    retriever = Retriever(EdgarClient("replay", settings))
    tickers = only or json.loads((REPO_ROOT / "config" / "test_tickers.json").read_text())["tickers"]
    results = []
    try:
        for t in tickers:
            cik = retriever.client.lookup_cik(t)[0]
            fs = assess_qualitative(cik, t, retriever, llm, trace)
            results.append(fs)
            print(f"{t}: " + ", ".join(f"{f.criterion.split('_')[0]}={SHORT[f.verdict]}" for f in fs.findings)
                  + f" | calls {fs.totals.llm_calls}, tokens {fs.totals.usage.total_tokens:,}", flush=True)
    except QuotaReached as e:
        print(f"STOPPED: {e}. Completed: {[r.ticker for r in results]}. No report written; rerun after the reset.")
        return 1
    OUT.write_text(render(results), encoding="utf-8")
    (TRACE_DIR / "qualitative_used_hashes.txt").write_text("\n".join(sorted({c.request_hash for c in llm.calls})) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}; {len(llm.calls)} model calls ({sum(not c.replayed for c in llm.calls)} over the network)")
    if mode == "record":
        ledger = Ledger(settings.ledger_path)
        print(f"ledger: requests {ledger.data['requests']} spend ${ledger.spend:.4f} notional ${ledger.data['notional_usd']:.6f}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else "replay", sys.argv[2:]))
