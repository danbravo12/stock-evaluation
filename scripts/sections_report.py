"""Extract Items 1, 1A and 7 from the 5 recorded 10-Ks (replay, no network) and write
docs/sections_report.md: per company and item the status, method, length and opening text
(so a table of contents would be obvious), then for each qualitative Buffett criterion the top 3
passages its starting queries find. This previews what the qualitative agent will see.

    .venv/bin/python scripts/sections_report.py
"""
from __future__ import annotations

import json
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from engine.fetch.edgar import EdgarClient  # noqa: E402
from engine.retrieve import Retriever  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402

OUT = REPO_ROOT / "docs" / "sections_report.md"
ITEM_NAMES = {"1": "Business", "1A": "Risk Factors", "7": "MD&A"}


def snippet(text: str, n: int = 200) -> str:
    return " ".join(text.split())[:n].replace("|", "\\|")


def main() -> None:
    client = EdgarClient("replay", Settings.from_env())
    retriever = Retriever(client)
    tickers = json.loads((REPO_ROOT / "config" / "test_tickers.json").read_text())["tickers"]
    criteria = json.loads((REPO_ROOT / "config" / "search_terms.json").read_text())["criteria"]

    lines = [
        "# Sections and retrieval report",
        "",
        "Generated by `scripts/sections_report.py` from the recorded 10-Ks (replay mode, no network). "
        "Offsets are into the normalised text (ADR-035). Data: U.S. Securities and Exchange Commission, EDGAR (public domain).",
        "",
        "## Sections found",
        "",
        "| Company | Item | Status | Method | Length (chars) | Passages | Opens with |",
        "|---|---|---|---|---|---|---|",
    ]
    indexes = {}
    for t in tickers:
        cik = client.lookup_cik(t)[0]
        t0 = time.time()
        idx = indexes[t] = retriever.index(cik)
        seconds = time.time() - t0
        for item, s in idx.sections.items():
            n = sum(p.item == item for p in idx.passages)
            opens = snippet(idx.text[s.char_start:s.char_end]) if s.status == "found" else s.reason
            lines.append(f"| {t} | {item} {ITEM_NAMES[item]} | {s.status} | {s.method or '-'} | {s.length:,} | {n} | {opens} |")
        print(f"{t}: {len(idx.passages)} passages in {seconds:.1f}s")

    lines += ["", "## What the search finds", "",
              "Top 3 passages per criterion, from its starting queries (`config/search_terms.json`) summed per passage. "
              "Not tuned to look good: weak results are weak.", ""]
    for t in tickers:
        cik = client.lookup_cik(t)[0]
        lines += [f"### {t}", ""]
        for name, spec in criteria.items():
            lines.append(f"**{name}** (items {', '.join(spec['items'])})")
            lines.append("")
            for h in retriever.search_many(cik, spec["queries"], spec["items"], k=3):
                lines.append(f"- `{h.passage_id}` score {h.score:.2f}, terms: {', '.join(h.matched_terms)} — {snippet(h.text)}")
            lines.append("")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {OUT.relative_to(REPO_ROOT)}")


if __name__ == "__main__":
    main()
