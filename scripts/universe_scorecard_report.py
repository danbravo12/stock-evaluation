"""Report on the whole-universe numeric run (ADR-059) -> docs/universe_scorecard_report.md. Reads results/scores/ (local, git-ignored) and the numeric ledger.

    .venv/bin/python scripts/universe_scorecard_report.py
"""
from __future__ import annotations

import json
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from eval.universe_counts import LABELS, SCORES_DIR, count_labels  # noqa: E402
from engine.settings import REPO_ROOT, Settings  # noqa: E402
from engine.universe import load_universe  # noqa: E402

OUT = REPO_ROOT / "docs" / "universe_scorecard_report.md"
SHORT = {"pass": "pass", "partial_pass": "partial", "fail": "fail", "not_applicable": "n/a", "not_meaningful": "n/m", "data_gap": "gap"}


def shape(text: str) -> str:
    """A note or reason with its numbers, years and amounts blanked, so similar ones group together."""
    return re.sub(r"\d[\d,.]*", "#", re.sub(r"\[[^\]]*\]", "[..]", text))[:160]


def table(rows: list[dict], cols: list[str], limit: int = 25) -> list[str]:
    L = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows[:limit]:
        L.append("| " + " | ".join(str(r.get(c, "")).replace("|", "\\|") for c in cols) + " |")
    if len(rows) > limit:
        L.append(f"| … {len(rows) - limit} more | " + " | " * (len(cols) - 2) + "|")
    return L


def main() -> int:
    u = load_universe()
    results = []
    for p in sorted(SCORES_DIR.glob("*.json")):
        if not p.name.startswith("_"):
            results.append(json.loads(p.read_text(encoding="utf-8")))
    ledger_path = Settings.from_env().ledger_path.with_name("numeric.json")
    ledger = json.loads(ledger_path.read_text()) if ledger_path.exists() else {}
    failed = sorted((r for r in ledger.values() if r["status"] == "failed"), key=lambda r: r["ticker"])
    run_file = SCORES_DIR / "_run_download.json"
    run = json.loads(run_file.read_text()) if run_file.exists() else json.loads((SCORES_DIR / "_run.json").read_text())
    counts = count_labels()
    L = ["# Universe scorecard report: numeric run over the S&P 500", "",
         f"{u.attribution}. Data: U.S. Securities and Exchange Commission, EDGAR (public domain). Generated by `scripts/universe_scorecard_report.py` from `results/scores/` "
         "(local, git-ignored; the frozen label counts are in `eval/universe_label_counts.json`). Research output, not financial advice. No model was used and no 10-K was downloaded; "
         "G6 and G7 are data gaps because there is no price yet.", "",
         "## The run", "",
         f"- Companies in the universe (one per CIK): **{len(u.primary)}**; scored: **{len(results)}**; failed: **{len(failed)}**.",
         f"- First (downloading) run: **{run.get('seconds_this_run', '?')} s**, **{run.get('edgar_requests_this_run', '?')}** EDGAR requests (submissions had been fetched earlier for the SIC list; throttled to about 6 requests a second, declared User-Agent).", ""]
    if failed:
        L += ["Failed companies:", ""] + [f"- {r['ticker']}: {r['message']}" for r in failed] + [""]
    L += ["## Label distribution per criterion", "",
          "\"% pass\" counts pass and partial pass over the companies where the criterion was decided (pass, partial, fail).", "",
          "| Criterion | " + " | ".join(SHORT[l] for l in LABELS) + " | % pass (decided) |", "|---|" + "---|" * (len(LABELS) + 1)]
    for cid, c in counts["criteria"].items():
        decided = c.get("pass", 0) + c.get("partial_pass", 0) + c.get("fail", 0)
        pct = f"{100 * (c.get('pass', 0) + c.get('partial_pass', 0)) / decided:.0f}% of {decided}" if decided else "–"
        L.append(f"| {cid} | " + " | ".join(str(c.get(l, 0)) for l in LABELS) + f" | {pct} |")
    L += ["", "## By sector class", "", "Companies per class: " + ", ".join(f"{k} {v}" for k, v in counts["sector_classes"].items()) + ".", ""]
    for cls, d in counts["by_sector_class"].items():
        L += [f"**{cls}**", "", "| Criterion | " + " | ".join(SHORT[l] for l in LABELS) + " |", "|---|" + "---|" * len(LABELS)]
        for cid, c in d.items():
            L.append(f"| {cid} | " + " | ".join(str(c.get(l, 0)) for l in LABELS) + " |")
        L.append("")
    # ---- data gaps
    gap_reasons, measure_gap = Counter(), Counter()
    for r in results:
        for c in r["score"]["results"]:
            if c["label"] == "data_gap" and c["id"] not in ("G6", "G7"):
                gap_reasons[(c["id"], shape(c.get("reason") or ""))] += 1
        for g in r["diagnostics"]["gaps"]:
            if g["year"] is None:
                measure_gap[(g["measure"], shape(g["reason"]))] += 1
    L += ["## Data gaps", "", f"G6 and G7 are data gaps for all {len(results)} companies (no price). Other criteria that ended as data gaps, by reason:", "",
          "| Criterion | Reason | Companies |", "|---|---|---|"] + [f"| {cid} | {reason} | {n} |" for (cid, reason), n in gap_reasons.most_common(25)]
    L += ["", "Whole-measure gaps in the normalised data (measure missing for the company), most common first:", "", "| Measure | Reason | Companies |", "|---|---|---|"]
    L += [f"| {m} | {reason} | {n} |" for (m, reason), n in measure_gap.most_common(25)]
    # ---- notes
    notes = Counter()
    for r in results:
        for n in r["diagnostics"]["notes"]:
            notes[(n["measure"], shape(n["note"]))] += 1
    L += ["", "## The 15 most common normaliser notes", "", "| Measure | Note (numbers blanked) | Occurrences |", "|---|---|---|"] + [f"| {m} | {t} | {n} |" for (m, t), n in notes.most_common(15)]
    # ---- anomalies
    def rows_for(key, fmt):
        out = []
        for r in results:
            v = r["diagnostics"][key]
            if v:
                out.append({"ticker": r["ticker"], "class": r["sector_class"], **fmt(v)})
        return out
    g4 = rows_for("g4_fail_with_13_or_more_paid", lambda v: {"years_on_record": v["years_on_record"], "unpaid_years": v["unpaid_years"], "dividends per share in those years": v["values"]})
    jumps = rows_for("revenue_jumps", lambda v: {"jumps (year: ratio)": "; ".join(f"{j['year']}: {j['ratio']}x" for j in v)})
    sign = rows_for("eps_sign_mismatch", lambda v: {"years (EPS vs net income)": "; ".join(f"{m['year']}: {m['eps']} vs {m['net_income']:,.0f}" for m in v)})
    # per-share and share-count measures are left out: companies restate them for splits themselves
    restated = rows_for("restated_over_10pct", lambda v: {"restatements": len(v), "largest": max(v, key=lambda x: x["change"])["measure"] + " " + str(max(v, key=lambda x: x["change"])["year"]) + f" {max(x['change'] for x in v):.0%}"})
    split_n = Counter()
    for r in results:
        for m in r["diagnostics"]["split_adjusted"]:
            split_n[m] += 1
    split_cos = [r for r in results if r["diagnostics"]["split_adjusted"]]
    L += ["", "## Anomalies that smell like mapping bugs", "",
          f"### G4 fails although a dividend was paid in at least 13 of the years on record ({len(g4)})", ""] + (table(g4, ["ticker", "class", "years_on_record", "unpaid_years", "dividends per share in those years"]) or ["none"]) + [""]
    L += [f"### Revenue jumps of more than 3x year on year ({len(jumps)} companies)", ""] + table(jumps, ["ticker", "class", "jumps (year: ratio)"]) + [""]
    L += [f"### Diluted EPS sign disagreeing with net income ({len(sign)} companies)", ""] + table(sign, ["ticker", "class", "years (EPS vs net income)"]) + [""]
    L += [f"### Restatements over 10% ({len(restated)} companies)", ""] + table(restated, ["ticker", "class", "restatements", "largest"]) + [""]
    L += [f"### Stock-split adjustment applied ({len(split_cos)} companies)", "", "Measures adjusted: " + ", ".join(f"{m} {n}" for m, n in split_n.most_common()) + ". Largest cumulative factors:", ""]
    big = sorted(({"ticker": r["ticker"], "max factor": max(v["max_factor"] for v in r["diagnostics"]["split_adjusted"].values())} for r in split_cos), key=lambda x: -x["max factor"])
    L += table(big, ["ticker", "max factor"], 12) + [""]
    OUT.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {len(results)} scored, {len(failed)} failed; anomalies: g4 {len(g4)}, jumps {len(jumps)}, sign {len(sign)}, restated {len(restated)}, split {len(split_cos)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
